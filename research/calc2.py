# -*- coding: utf-8 -*-
MON=[(3000,.03,0),(12000,.10,210),(25000,.20,1410),(35000,.25,2660),(55000,.30,4410),(80000,.35,7160),(10**12,.45,15160)]
ANN=[(36000,.03,0),(144000,.10,2520),(300000,.20,16920),(420000,.25,31920),(660000,.30,52920),(960000,.35,85920),(10**12,.45,181920)]
LAB=[(20000,.20,0),(50000,.30,2000),(10**12,.40,7000)]
def rb(x,tb):
    for cap,r,d in tb:
        if x<=cap: return r,d
def bonus(B):
    r,d=rb(B/12.0,MON); return B*r-d
def T(x,tb):
    if x<=0: return 0.0
    r,d=rb(x,tb); return x*r-d
print("== 盲区 ==")
for m,_,_ in MON[:-1]:
    b=m*12; tax=bonus(b); net=b-tax
    r,d=rb(b+1,MON); Bp=(net-d)/(1-r)
    print(f"临界{b} 税额{tax:.0f} 税后{net:.0f} 盲区({b},{Bp:.2f}] 宽{Bp-b:.2f} 税后降{net-(Bp-(Bp*r-d)):+.0f}")
print("== 单独 vs 并入 ==")
for X in [0,36000,100000,200000,400000]:
    s=[]
    for B in [36000,100000,200000,500000]:
        sep=bonus(B); mg=T(X+B,ANN)-T(X,ANN); s.append(f"{B}:单{sep:.0f}/并{mg:.0f}/并入省{mg-sep:+.0f}")
    print(f"X={X}"," | ".join(s))
print("== 劳务报酬 ==")
for R in [30000,60000,120000,300000]:
    w=T(R*0.8,LAB); f=T(R*0.8-60000,ANN)
    print(f"{R}: 预扣{w:.0f} 汇算{f:.0f} 退{w-f:.0f}")
print("== 稿酬 ==")
for R in [20000,100000]:
    w=T(R*0.8*0.7,[(10**12,.20,0)]); f=T(R*0.8*0.7-60000,ANN)
    print(f"{R}: 预扣{w:.0f} 汇算{f:.0f}")
print("== 股权激励（单独，年取得G）==")
for G in [100000,500000,1000000]:
    print(f"{G}: 税{T(G,ANN):.0f}")
