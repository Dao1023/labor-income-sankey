# -*- coding: utf-8 -*-
ANN=[(36000,.03,0),(144000,.10,2520),(300000,.20,16920),(420000,.25,31920),(660000,.30,52920),(960000,.35,85920),(10**12,.45,181920)]
MON=[(3000,.03,0),(12000,.10,210),(25000,.20,1410),(35000,.25,2660),(55000,.30,4410),(80000,.35,7160),(10**12,.45,15160)]
LAB=[(20000,.20,0),(50000,.30,2000),(10**12,.40,7000)]
BIZ=[(30000,.05,0),(90000,.10,1500),(300000,.20,10500),(500000,.30,40500),(10**12,.35,65500)]
def t(x,tb):
    if x<=0: return 0.0
    for cap,r,d in tb:
        if x<=cap: return x*r-d
def bonus(B): return t(B/12.0,MON)
print("== 盲区 ==")
bounds=[b for b,_,_ in MON[:-1]]
for b in bounds:
    tax=t(b/12.0,MON); net=b-tax
    cap,r,d=[x for x in MON if x[0]>b/12.0][0]
    # solve B - (B*r-d) = net
    Bp=(net-d)/(1-r)
    extra=Bp-b
    print(f"临界{b}元 税额{tax:.0f} 税后{net:.0f} -> 盲区({b}, {Bp:.2f}] 宽度{extra:.2f} 跳档多缴{t(Bp/12.0,MON)-tax:.0f}")
print("== 单独 vs 并入（综合所得应纳税所得额X，年终奖B）==")
for X in [0,36000,100000,200000,400000]:
    row=[]
    for B in [36000,100000,200000,500000]:
        sep=bonus(B); merge=t(X+B,ANN)-t(X,ANN)
        row.append(f"B={B}: 单{sep:.0f}/并{merge:.0f}/差{sep-merge:+.0f}")
    print(f"X={X}", " | ".join(row))
print("== 劳务报酬预扣 vs 汇算（单人仅劳务，年入R）==")
for R in [30000,60000,120000,300000]:
    w=t(R*0.8,LAB)  # 简化：全部按一次预扣
    fin=t(R*0.8-60000,ANN)
    print(f"年劳务收入{R}: 预扣{w:.0f} 汇算{fin:.0f} 退税{w-fin:.0f}")
print("== 经营所得（个体户，仅经营所得，无综合所得）==")
for P in [100000,200000,500000,1000000]:
    tax=t(P-60000,BIZ); half=tax/2
    print(f"应纳税所得额(收入-成本-60000后){P-60000}: 税{tax:.0f} 减半(≤200万部分,2023-2027){max(0,tax - (t(min(P,2000000)-60000,BIZ)/2 if False else 0)):.0f}")
